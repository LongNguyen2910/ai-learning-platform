import uuid
from datetime import date, datetime

from pydantic import BaseModel, ConfigDict, Field, field_validator


class RawStudyTopic(BaseModel):
    """Pydantic schema representing a topic extracted by LLM from curriculum."""

    title: str = Field(description="Tiêu đề chủ đề hoặc bài học chi tiết")
    description: str | None = Field(default="", description="Tóm tắt nội dung chính")
    target_page_start: int = Field(ge=1, description="Trang bắt đầu trong tài liệu")
    target_page_end: int = Field(ge=1, description="Trang kết thúc trong tài liệu")
    is_core: bool = Field(
        default=True,
        description="True nếu là kiến thức cốt lõi/bắt buộc, False nếu nâng cao/phụ lục",
    )
    complexity_level: int = Field(
        default=2,
        ge=1,
        le=3,
        description="1: Dễ/Khái niệm, 2: Trung bình/Ứng dụng, 3: Phức tạp/Toán sâu",
    )


class RawChapterOutline(BaseModel):
    """Pydantic schema representing a chapter/module extracted by LLM."""

    title: str = Field(description="Tên chương hoặc module lớn")
    description: str | None = Field(default="", description="Tổng quan chương")
    target_page_start: int = Field(ge=1, description="Trang bắt đầu chương")
    target_page_end: int = Field(ge=1, description="Trang kết thúc chương")
    topics: list[RawStudyTopic] = Field(
        default_factory=list, description="Danh sách các chủ đề con"
    )


class RawCurriculumOutline(BaseModel):
    """Overall curriculum structure generated by Gemini Structured Output."""

    title: str = Field(description="Tiêu đề tổng thể của tài liệu hoặc khóa học")
    summary: str | None = Field(default="", description="Mô tả tóm lược")
    chapters: list[RawChapterOutline] = Field(
        default_factory=list, description="Danh sách các chương"
    )


class RoadmapGenerateRequest(BaseModel):
    """DTO for initiating initial roadmap tree generation (FR-12)."""

    subject_id: uuid.UUID
    document_id: uuid.UUID
    title: str = Field(min_length=2, max_length=255)
    target_date: date
    available_hours_per_day: float = Field(default=2.0, ge=0.5, le=12.0)
    study_goal: str | None = Field(
        default=None,
        description="Mục tiêu cụ thể của người học (ví dụ: thi qua môn điểm A, nắm chắc chương 1-3)",
    )

    @field_validator("target_date")
    @classmethod
    def validate_target_date(cls, v: date) -> date:
        if v <= date.today():
            raise ValueError("target_date must be in the future.")
        return v


class RoadmapNodeResponse(BaseModel):
    """DTO representing a single hierarchical node in the Roadmap Tree."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    roadmap_id: uuid.UUID
    parent_node_id: uuid.UUID | None = None
    document_id: uuid.UUID | None = None
    title: str
    description: str | None = None
    order_index: int
    target_page_start: int | None = None
    target_page_end: int | None = None
    estimated_minutes: int
    is_unlocked: bool
    is_completed: bool
    completed_at: datetime | None = None
    children: list["RoadmapNodeResponse"] = Field(default_factory=list)


class RoadmapResponse(BaseModel):
    """DTO representing basic roadmap metadata."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    user_id: uuid.UUID
    subject_id: uuid.UUID
    title: str
    target_date: date | None = None
    available_hours_per_day: float
    progress_percentage: float
    status: str
    created_at: datetime


class RoadmapTreeResponse(BaseModel):
    """Full 3-tier hierarchical tree response for /roadmap endpoint."""

    roadmap: RoadmapResponse
    tree: list[RoadmapNodeResponse]
    total_nodes: int
    total_estimated_minutes: int


class RoadmapTaskStatusResponse(BaseModel):
    """DTO for polling the asynchronous generation status."""

    task_id: str
    roadmap_id: uuid.UUID | None = None
    status: str
    progress_percent: int
    message: str
    error: str | None = None
